#!/usr/bin/env python3
"""GUSTAVA approved DEEP narrator: AI Doc Maker's exact Create Audio Voice preset.

This module consumes only a voiceover ALREADY generated by the authorized
AI Voice Generator ChatGPT app with voice_id='deep'. It does not impersonate,
clone, remap or synthesize a supposedly equivalent voice. There is currently
no confirmed provider API for unattended new speech generation. Missing audio
means NOT READY, never substitute the seven rejected voices.
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path
import re
import subprocess
import urllib.parse
import urllib.request
import wave

VOICE_ENGINE = "aidocmaker_deep"
PROFILE_ID = "gustava_create_audio_deep_v1"
VOICE_ID = "deep"
PROVIDER = "AI Doc Maker"
SOURCE_HOST = "storage.googleapis.com"
PATH_RE = re.compile(
    r"/adm--audio-playback--7d--public/mcp-preview/"
    r"[0-9a-f]{8}-[0-9a-f-]{27,36}\.mp3\Z")
MAX_BYTES = 6_000_000
SAMPLE_RATE = 24000


def digest(data):
    return hashlib.sha256(data).hexdigest()


def approved_asset(asset, transcript):
    if not isinstance(asset, dict):
        raise ValueError("GUSTAVA_DEEP_AUDIO_MISSING: no approved Create Audio Voice recording")
    if (asset.get("provider") != "aidocmaker.com"
            or asset.get("voice_id") != VOICE_ID
            or asset.get("transcript_sha256") != digest(transcript.encode("utf-8"))):
        raise ValueError("GUSTAVA_DEEP_AUDIO_MISMATCH: wrong preset or changed script")
    url = urllib.parse.urlsplit(asset.get("preview_url") or "")
    if (url.scheme != "https" or url.hostname != SOURCE_HOST
            or not PATH_RE.fullmatch(url.path) or url.query
            or url.username or url.password or url.port):
        raise ValueError("GUSTAVA_DEEP_AUDIO_UNTRUSTED_URL")
    return url.geturl()


def ready(episode):
    """No automatic render without one exact pre-generated, hash-pinned DEEP file."""
    if episode.get("voice_engine") != VOICE_ENGINE:
        return False
    asset = episode.get("deep_audio")
    try:
        approved_asset(asset, episode["narration"])
    except (KeyError, ValueError, TypeError):
        return False
    return bool(re.fullmatch(r"[0-9a-f]{64}", asset.get("source_audio_sha256") or ""))


# Free-tier public uses must carry this provider's published attribution.
# Keep it while commercial subscription status is unverified.
PUBLIC_ATTRIBUTION = (
    "Voiceover Generated with AIDOCMAKER.COM: https://www.aidocmaker.com"
)


def provenance_path(wav):
    return Path(wav).with_suffix(".profile.json")


def pcm_stats(wav):
    import array
    import math
    with wave.open(str(wav), "rb") as f:
        if (f.getnchannels(), f.getsampwidth(), f.getframerate()) != (1, 2, SAMPLE_RATE):
            raise ValueError("DEEP_STUDIO_PCM_NOT_24K_MONO")
        frames = f.getnframes()
        duration = frames / SAMPLE_RATE
        samples = array.array("h")
        samples.frombytes(f.readframes(frames))
    if not 3.0 <= duration <= 35.0:
        raise ValueError("GUSTAVA_DEEP_DURATION_UNSUITABLE")
    if not samples:
        raise ValueError("GUSTAVA_DEEP_SILENCE")
    peak = max(abs(x) for x in samples) / 32768
    clipped = sum(abs(x) >= 32700 for x in samples) / len(samples)
    energy = math.sqrt(sum((x / 32768.)**2 for x in samples) / len(samples))
    if peak < .02 or energy < .008 or peak > .999 or clipped > .002:
        raise ValueError("GUSTAVA_DEEP_AUDIO_SIGNAL_QUALITY_FAILED")
    return {"duration_seconds": round(duration, 3),
            "peak": round(peak, 5), "rms": round(energy, 5),
            "clipped_fraction": round(clipped, 6)}


def verify_profile(wav, episode):
    file = Path(wav)
    profile = provenance_path(file)
    if not profile.is_file():
        raise ValueError("GUSTAVA_DEEP_PROFILE_MISSING")
    report = json.loads(profile.read_text(encoding="utf-8"))
    if episode.get("voice_engine") != VOICE_ENGINE:
        raise ValueError("GUSTAVA_DEEP_WRONG_VOICE_ENGINE")
    asset = episode.get("deep_audio")
    approved_asset(asset, episode["narration"])
    if (report.get("voice_id") != VOICE_ID
            or report.get("voice_profile") != PROFILE_ID
            or report.get("provider") != PROVIDER
            or report.get("episode_id") != episode["id"]
            or report.get("transcript_sha256") != asset["transcript_sha256"]
            or report.get("source_url") != asset["preview_url"]
            or report.get("output_sha256") != digest(file.read_bytes())
            or report.get("source_audio_sha256") != asset.get("source_audio_sha256")):
        raise ValueError("GUSTAVA_DEEP_PROVENANCE_MISMATCH")
    stats = pcm_stats(file)
    if abs(report["duration_seconds"] - stats["duration_seconds"]) > .02:
        raise ValueError("GUSTAVA_DEEP_DURATION_MISMATCH")
    return report


def render(episode, destination, ffmpeg="ffmpeg"):
    """Download *this episode's* authorized DEEP audio; never a reusable demo."""
    transcript = episode["narration"]
    source = approved_asset(episode.get("deep_audio"), transcript)
    asset = episode["deep_audio"]
    source_hash = asset.get("source_audio_sha256")
    if not isinstance(source_hash, str) or not re.fullmatch(r"[0-9a-f]{64}", source_hash):
        raise ValueError("GUSTAVA_DEEP_SOURCE_SHA256_NOT_PINNED")
    dst = Path(destination)
    dst.parent.mkdir(parents=True, exist_ok=True)
    raw = dst.with_name(dst.stem + ".approved-deep.mp3")
    temp = dst.with_name(dst.stem + ".approved-deep.tmp.wav")
    sidecar = provenance_path(dst)
    sidecar.unlink(missing_ok=True)
    try:
        req = urllib.request.Request(
            source, headers={"User-Agent":"GUSTAVA-Approved-Deep-Voice/1.0"})
        with urllib.request.urlopen(req, timeout=45) as response:
            if urllib.parse.urlsplit(response.geturl()).hostname != SOURCE_HOST:
                raise ValueError("GUSTAVA_DEEP_UNEXPECTED_REDIRECT")
            content = response.read(MAX_BYTES + 1)
        if not 20000 <= len(content) <= MAX_BYTES:
            raise ValueError("GUSTAVA_DEEP_FILE_SIZE_OUTSIDE_LIMITS")
        if digest(content) != source_hash:
            raise ValueError("GUSTAVA_DEEP_SOURCE_HASH_CHANGED")
        if not (content.startswith(b"ID3") or content[0] == 0xff):
            raise ValueError("GUSTAVA_DEEP_SOURCE_NOT_MP3")
        raw.write_bytes(content)
        subprocess.run(
            [ffmpeg, "-hide_banner", "-nostdin", "-loglevel", "error", "-y",
             "-i", str(raw), "-vn", "-ac", "1", "-ar", str(SAMPLE_RATE),
             "-c:a", "pcm_s16le", str(temp)],
            check=True, capture_output=True, text=True, timeout=90)
        stats = pcm_stats(temp)
        temp.replace(dst)
        report = {
            "episode_id": episode["id"], "voice_id": VOICE_ID,
            "voice_profile": PROFILE_ID, "provider": PROVIDER,
            "speaker": "deep", "source_url": source,
            "transcript_sha256": asset["transcript_sha256"],
            "source_audio_sha256": source_hash,
            "output_sha256": digest(dst.read_bytes()),
            "duration_seconds": stats["duration_seconds"],
            "pitch_shift": 1.0,
            "voice_layers": 1,
            "human_voice_match": "exact provider deep preset, no cloning",
        }
        sidecar.write_text(
            json.dumps(report, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8")
        verify_profile(dst, episode)
        print("GUSTAVA_APPROVED_CREATE_AUDIO_DEEP_READY",
              episode["id"], "duration", stats["duration_seconds"], flush=True)
        return stats["duration_seconds"]
    finally:
        raw.unlink(missing_ok=True)
        temp.unlink(missing_ok=True)
